//go:build darwin

package mac

import (
	"sync/atomic"

	"github.com/ebitengine/purego/objc"
)

// ownCopy is the general pasteboard's change count after Mega Voice's own
// last copy; -1 before the first.
var ownCopy atomic.Int64

func init() { ownCopy.Store(-1) }

// Clipboard is the general pasteboard as the model step's clipboard source
// reads it (refine.Pasteboard).
type Clipboard struct{}

// Count is the pasteboard's change count, and whether what it holds is
// Mega Voice's own last copy.
func (Clipboard) Count() (count int, own bool) {
	DoSync(func() { count = sendInt(send(class("NSPasteboard"), "generalPasteboard"), "changeCount") })
	return count, int64(count) == ownCopy.Load()
}

// concealed are the pasteboard types a copier marks a secret or a passing
// copy with (nspasteboard.org): a password manager's copy carries them.
var concealed = []string{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
	"com.agilebits.onepassword"}

// Text is the plain text on the pasteboard; ok is false when it holds none
// or carries a concealed or transient mark.
func (Clipboard) Text() (text string, ok bool) {
	DoSync(func() {
		pb := send(class("NSPasteboard"), "generalPasteboard")
		types := send(pb, "types")
		for _, t := range concealed {
			if types != 0 && sendBool(types, "containsObject:", nsString(t)) {
				return
			}
		}
		s := send(pb, "stringForType:", nsString("public.utf8-plain-text"))
		if s == 0 {
			return
		}
		text, ok = goString(objc.ID(s)), true
	})
	return text, ok
}

// SecureInput reports whether the system's secure keyboard input is on: a
// password field has the keyboard, or a terminal's Secure Keyboard Entry.
func SecureInput() bool { return isSecureEventInputEnabled() }

// PasswordField reports whether the captured element is a password field.
// Without the Accessibility grant it asks nothing (passwordFocused).
func (a App) PasswordField() (secure bool) {
	if a.Element == 0 || !axIsProcessTrusted() {
		return false
	}
	WithPool(func() {
		sub := axCopy(a.Element, "AXSubrole")
		if sub == 0 {
			return
		}
		defer cfRelease(sub)
		secure = goString(objc.ID(sub)) == "AXSecureTextField"
	})
	return secure
}
