package refine

import (
	"bytes"
	"flag"
	"os"
	"strings"
	"testing"
)

var updatePinyin = flag.Bool("update-pinyin", false, "regenerate the iPhone's pinyin table")

// pinyinTable is where the iPhone keeps the readings the glossary's matching
// hears Chinese characters by (reading), outside the public tree.
const pinyinTable = "../../ios/MegaVoiceKit/Sources/Refine/PinyinTable.swift"

// pinyinSwift is reading for every character of U+4E00–U+9FFF as the
// iPhone's Swift source holds it: one reading per character in order, 64 to
// a line, "" for a character with none.
func pinyinSwift() []byte {
	var b bytes.Buffer
	b.WriteString("// Generated by `go test ./internal/refine -run TestPinyinTable -update-pinyin`: go-pinyin's\n")
	b.WriteString("// reading of each character of U+4E00–U+9FFF (internal/refine/sound.go reading), 64 to a\n")
	b.WriteString("// line, empty where it has none. Do not edit.\n\n")
	b.WriteString("enum PinyinTable {\n    static let first: UInt32 = 0x4E00\n    static let readings = \"\"\"\n")
	var line []string
	for c := rune(0x4e00); c <= 0x9fff; c++ {
		r := ""
		if p := reading(c); p != string(c) {
			r = p
		}
		line = append(line, r)
		if len(line) == 64 || c == 0x9fff {
			b.WriteString(strings.Join(line, " "))
			b.WriteByte('\n')
			line = line[:0]
		}
	}
	b.WriteString("\"\"\"\n}\n")
	return b.Bytes()
}

// The iPhone hears a character as this package does: its table is reading,
// generated. The public tree has no ios/, and there is nothing to compare.
func TestPinyinTable(t *testing.T) {
	for c := rune(0x4e00); c <= 0x9fff; c++ {
		p := reading(c)
		if p == string(c) {
			continue
		}
		for i := 0; i < len(p); i++ {
			if p[i] < 'a' || p[i] > 'z' {
				t.Fatalf("reading of %c is %q: the table holds lower-case ASCII readings", c, p)
			}
		}
	}
	want := pinyinSwift()
	if *updatePinyin {
		if err := os.WriteFile(pinyinTable, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(pinyinTable)
	if os.IsNotExist(err) {
		t.Skip("no iPhone sources in this tree")
	}
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is not go-pinyin's readings now: run go test ./internal/refine -run TestPinyinTable -update-pinyin", pinyinTable)
	}
}
